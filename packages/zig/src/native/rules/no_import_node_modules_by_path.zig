//! `pickier/no-import-node-modules-by-path` - port of
//! packages/pickier/src/rules/imports/no-import-node-modules-by-path.ts
//!
//! A single-line `import ... from '<src>'` or `require('<src>')` whose source
//! contains `/node_modules/`.

const std = @import("std");
const types = @import("../types.zig");
const text = @import("../text.zig");
const import_source = @import("st_import_source.zig");

pub fn check(ctx: *const types.RuleContext, out: *std.ArrayList(types.Issue)) anyerror!void {
    const a = ctx.allocator;
    const lines = try text.splitLines(a, ctx.content);
    for (lines, 0..) |line, i| {
        // Neither pattern matches without its word
        const has_import = std.mem.indexOf(u8, line, "import") != null;
        if (!has_import and std.mem.indexOf(u8, line, "require(") == null) continue;
        // `mi?.[1] || mr?.[1]`
        const src = (if (has_import) import_source.importSource(line) else null) orelse
            requireSource(line) orelse continue;
        if (std.mem.indexOf(u8, src, "/node_modules/") == null) continue;
        const at = std.mem.indexOf(u8, line, src).?;
        try out.append(a, .{
            .line = @intCast(i + 1),
            .column = @intCast(text.utf16Index(line, at) + 1),
            .rule_id = "pickier/no-import-node-modules-by-path",
            .message = "Do not import modules in `node_modules` folder by path",
            .severity = .@"error",
        });
    }
}

/// `/require\(\s*['"]([^'"]+)['"]\s*\)/`: the capture of the first match.
fn requireSource(line: []const u8) ?[]const u8 {
    var from: usize = 0;
    while (std.mem.indexOfPos(u8, line, from, "require(")) |k| {
        from = k + 1;
        const src = import_source.quotedAfter(line, k + "require(".len) orelse continue;
        const close = @intFromPtr(src.ptr) - @intFromPtr(line.ptr) + src.len;
        var j = close + 1;
        while (j < line.len) {
            const n = text.whitespaceLenAt(line, j);
            if (n == 0) break;
            j += n;
        }
        if (j < line.len and line[j] == ')') return src;
    }
    return null;
}
